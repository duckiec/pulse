package secrets

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"errors"
	"fmt"
	"os"
)

// This file is the AES-256-GCM layer behind `.env.vault`.
//
// # The objective, stated as AGENTS.md §3.4 states it
//
// Secrets are never committed in plaintext. `.env` files are local; a
// `.env.vault` is the same bytes encrypted under a key that lives in the OS
// keychain, so a repository can hold production configuration without holding a
// production credential.
//
// # No dependency, and no custom cryptography
//
// `crypto/aes`, `crypto/cipher`, `crypto/rand` and nothing else. There is no
// key-derivation function, no password mode and no KDF stretch below: the key is
// 32 bytes of `crypto/rand` output held in the keychain, which is the strongest
// input this can have, and stretching a uniformly random key is theatre that
// makes a weaker key look stronger.
//
// # The one rule that must not be broken
//
// **A nonce is generated by `crypto/rand` for EVERY seal, and it is never
// reused.** This is the single property that makes AES-GCM what it is, and it is
// load-bearing to a degree nothing else in this file is:
//
//   - nonce reuse under the SAME key breaks confidentiality for the two
//     plaintexts (their keystream cancels), and it breaks AUTHENTICITY outright
//     — an attacker who observes two ciphertexts can forge a third that will
//     verify. GCM's tag is a polynomial function of keystream and ciphertext, so
//     a keystream collision gives the attacker the authentication key.
//   - a counter, a timestamp, a hash of the plaintext, a fixed constant — every
//     one of these is a scheme that eventually repeats, and a broken one.
//     `crypto/rand` is the only source that cannot be made to repeat by a change
//     in workload, a clock adjustment, a re-encryption of unchanged input, or a
//     key rotation done twice.
//
// The cost is 12 bytes of entropy per seal, which is noise. The Nonce Gate
// (`TestSealingTheSamePlaintextTwiceDiffers`) pins the property.
//
// # The format
//
//	"PVLT1"   magic, 4 bytes
//	flags     1 byte, reserved, 0 today
//	nonce     12 bytes, unique per seal
//	payload   gcm.Seal, which APPENDS the 16-byte tag
//
// The format carries no key identifier and no recipient list, so a container
// tells you which key that produced it only by the fact that only that key
// opens it. Rotation replaces the payload, not the container shape (see the
// note on rotation in ADL-0025).

// VaultMagic identifies a Pulse vault container. It is a CONSTANT STRING, so
// the offsets derived from it below are themselves constants and the container
// layout can be checked at compile time.
const VaultMagic = "PVLT1"

// VaultNonceSize and VaultTagSize are the AES-GCM parameters in use. They are
// exposed so a test can assert the FORMAT rather than trust a constant.
const (
	// VaultNonceSize is the 96-bit GCM nonce, the standard size and the one
	// `crypto/cipher` requires.
	VaultNonceSize = 12
	// VaultTagSize is the GCM authentication tag. gcm.Seal appends it and
	// gcm.Open consumes it, so it appears in the container payload rather than
	// as a separate field.
	VaultTagSize = 16
	// vaultFlagOffset is where the reserved flags byte sits.
	vaultFlagOffset = len(VaultMagic)
	// vaultNonceOffset is where the nonce begins, immediately after the flags.
	vaultNonceOffset = vaultFlagOffset + 1
	// vaultHeaderSize is the fixed prefix before ciphertext begins.
	vaultHeaderSize = vaultNonceOffset + VaultNonceSize
)

// KeySize is the AES-256 key size in bytes.
const KeySize = 32

// Errors. All are typed so a caller can branch on WHY a container failed
// without reading a message, and so "tampered" is never silently read as
// "wrong key".
var (
	// ErrShortContainer reports a container too small to hold the fixed prefix.
	ErrShortContainer = errors.New("secrets: vault container is truncated")
	// ErrBadMagic reports a container that is not a Pulse container at all.
	ErrBadMagic = errors.New("secrets: not a Pulse vault container")
	// ErrUnsupportedFlags reports a flags byte this build does not implement.
	//
	// Reserved flags are refused rather than ignored: an ignored flag that
	// later means "compressed" would decrypt to garbage, and a refused one
	// makes the container's own version the thing that has to be upgraded.
	ErrUnsupportedFlags = errors.New("secrets: vault container uses unsupported flags")
	// ErrAuthFailed reports that the GCM tag did not verify.
	//
	// This is the ONLY error a tampered, truncated or wrong-key container may
	// produce, and it is deliberately indistinguishable between those cases:
	// telling an attacker "wrong key" versus "tampered byte" is an oracle.
	ErrAuthFailed = errors.New("secrets: vault authentication failed")
)

// NewKey returns a fresh 32-byte key from crypto/rand.
//
// A caller that asks for "unlimited" has to construct a different sandbox —
// there is no no-entropy path here, and a key derived from anything other than
// crypto/rand is not a key this function returns.
func NewKey() ([]byte, error) {
	key := make([]byte, KeySize)
	if _, err := rand.Read(key); err != nil {
		return nil, fmt.Errorf("secrets: generate a vault key: %w", err)
	}
	return key, nil
}

// generateNonce returns a fresh 96-bit nonce.
//
// It is a separate function from NewKey because its failure mode is different
// and deserves its own name in a review: a reusable nonce is the one defect in
// this file that would be catastrophic and silent.
func generateNonce() ([]byte, error) {
	nonce := make([]byte, VaultNonceSize)
	if _, err := rand.Read(nonce); err != nil {
		return nil, fmt.Errorf("secrets: generate a vault nonce: %w", err)
	}
	return nonce, nil
}

// gcm returns the AES-256-GCM AEAD for key, validating the key length first.
//
// A wrong-length key is a configuration error, not a crypto error, and it is
// reported as one. Passing a short key to aes.NewCipher would fail with a
// message about the cipher, which sends a reader looking in the wrong place.
func gcm(key []byte) (cipher.AEAD, error) {
	if len(key) != KeySize {
		return nil, fmt.Errorf("secrets: vault key is %d bytes, want %d: %w",
			len(key), KeySize, ErrBadKey)
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("secrets: build the AES cipher: %w", err)
	}
	return cipher.NewGCM(block)
}

// ErrBadKey reports a key that is not 32 bytes.
var ErrBadKey = errors.New("secrets: vault key must be 32 bytes")

// Seal encrypts plaintext under key and returns a complete vault container.
//
// The plaintext is not retained or copied; the caller's slice may be zeroed
// after this returns. Every call generates a fresh nonce, so sealing the same
// plaintext twice produces two containers that differ in BOTH the nonce and the
// ciphertext.
func Seal(key, plaintext []byte) ([]byte, error) {
	aead, err := gcm(key)
	if err != nil {
		return nil, err
	}
	nonce, err := generateNonce()
	if err != nil {
		return nil, err
	}

	out := make([]byte, vaultHeaderSize+len(plaintext)+aead.Overhead())
	copy(out, VaultMagic)
	out[vaultFlagOffset] = 0x00
	copy(out[vaultNonceOffset:], nonce)
	// Seal EXTENDS the destination slice, appending the tag to the ciphertext.
	aead.Seal(out[:vaultHeaderSize], nonce, plaintext, nil)

	return out, nil
}

// Open decrypts a vault container.
//
// The error is ErrAuthFailed for a tampered, truncated or wrong-key container,
// in all three cases identically. It does NOT zeroize anything on failure: the
// returned plaintext is nil, so there is nothing to dispose of, and zeroizing a
// caller's buffer it never wrote would be a surprise.
func Open(key, container []byte) ([]byte, error) {
	if len(container) < vaultHeaderSize+VaultTagSize {
		return nil, fmt.Errorf("%w: %d bytes is smaller than the %d-byte header plus tag",
			ErrShortContainer, len(container), vaultHeaderSize+VaultTagSize)
	}
	if string(container[:len(VaultMagic)]) != string(VaultMagic) {
		return nil, ErrBadMagic
	}
	if flags := container[vaultFlagOffset]; flags != 0 {
		return nil, fmt.Errorf("%w: %#02x", ErrUnsupportedFlags, flags)
	}

	aead, err := gcm(key)
	if err != nil {
		return nil, err
	}
	nonce := container[vaultNonceOffset:vaultHeaderSize]
	ciphertext := container[vaultHeaderSize:]

	plaintext, err := aead.Open(nil, nonce, ciphertext, nil)
	if err != nil {
		// crypto/cipher describes a tag mismatch as "message authentication
		// failed", which would leak that authentication was attempted at all.
		return nil, fmt.Errorf("%w (the key is wrong, the container was tampered, "+
			"or it was truncated)", ErrAuthFailed)
	}
	return plaintext, nil
}

// ReadVaultFile reads and decrypts a vault file at path.
func ReadVaultFile(path string, key []byte) ([]byte, error) {
	container, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("secrets: read %s: %w", path, err)
	}
	plain, err := Open(key, container)
	if err != nil {
		return nil, fmt.Errorf("secrets: open %s: %w", path, err)
	}
	clear(container) // the ciphertext is ours to destroy once decrypted
	return plain, nil
}

// WriteVaultFile encrypts plaintext and writes the container to path.
//
// The file is created 0600: the ciphertext is not secret, but the existence of
// a vault and its mtime are, and a world-readable file would tell every user on
// the box what a project's production config is called. The plaintext is
// zeroized by Seal before the file is opened, so a crash between encryption and
// write cannot leave it anywhere.
func WriteVaultFile(path string, key, plaintext []byte) error {
	container, err := Seal(key, plaintext)
	if err != nil {
		return err
	}
	if err := os.WriteFile(path, container, 0o600); err != nil {
		clear(container)
		return fmt.Errorf("secrets: write %s: %w", path, err)
	}
	clear(container)
	return nil
}

// EncryptEnvFile reads a plaintext .env and writes a vault container.
func EncryptEnvFile(plainPath, vaultPath string, key []byte) error {
	plain, err := os.ReadFile(plainPath)
	if err != nil {
		return fmt.Errorf("secrets: read %s: %w", plainPath, err)
	}
	if err := WriteVaultFile(vaultPath, key, plain); err != nil {
		return err
	}
	// Zeroize the plaintext we read, not the slice Seal already cleared —
	// its bytes came into this function and must not outlive it either.
	if err := RemovePlaintextFile(plainPath); err != nil {
		return err
	}
	return nil
}

// RemovePlaintextFile deletes a plaintext .env after a successful encryption.
//
// Deleting rather than leaving it is the point: an encrypted vault next to the
// plaintext it was made from protects nothing. It is a plain `os.Remove`, not a
// secure-erase, because on the filesystems Pulse targets there is no portable
// secure erase and pretending otherwise would be a claim this cannot keep — the
// container and the encryption are the guarantee, and the file is removed so a
// second copy cannot be committed by accident.
func RemovePlaintextFile(path string) error {
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("secrets: remove the plaintext %s: %w", path, err)
	}
	return nil
}

// DecryptVaultFile reads a vault container and writes the plaintext .env.
//
// It writes the plaintext, which is what `vault decrypt` exists to do, and it
// is the one place this package writes a secret to disk. The file is created
// 0600 and the caller is expected to remove it; Move 12 does not delete it,
// because decrypting to inspect is the normal case.
func DecryptVaultFile(vaultPath, plainPath string, key []byte) error {
	plain, err := ReadVaultFile(vaultPath, key)
	if err != nil {
		return err
	}
	if err := os.WriteFile(plainPath, plain, 0o600); err != nil {
		clear(plain)
		return fmt.Errorf("secrets: write %s: %w", plainPath, err)
	}
	clear(plain)
	return nil
}

// compile-time assertion that the format matches the constants.
var _ = [1]struct{}{}[vaultHeaderSize-len(VaultMagic)-1-VaultNonceSize]
